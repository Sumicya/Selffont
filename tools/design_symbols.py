def _wavy(x0, y0, y1, amp, turns=3):
    """垂直波浪中线：n 段二次贝塞尔，交替左右摆。"""
    p = pathops.Path()
    p.moveTo(x0, y0)
    seg = (y1 - y0) / turns
    sign = 1.0
    for i in range(turns):
        ya = y0 + seg * i
        yb = ya + seg
        p.quadTo(x0 + sign * amp, (ya + yb) / 2, x0, yb)
        sign = -sign
    return p


