def _stroked(strokes, hw):
    """贝塞尔中线 → 轮廓：2×半宽、圆端头、圆转角，所有笔画并成一条路径。

    `curves` 的每条笔画是一串首尾相接的三次贝塞尔段（每段 4 个控制点）。
    圆端头 + 圆转角 ⇒ 轮廓是「中线与半径 hw 的圆的闵可夫斯基和」，
    端头在构造上就是半圆、拐角在构造上就是圆弧，没有需要事后修的小角度。
    """
    acc = pathops.Path()
    for item in strokes:
        segs = item["segs"] if isinstance(item, dict) else item
        p = pathops.Path()
        p.moveTo(*segs[0][0])
        for seg in segs:
            p.cubicTo(*seg[1], *seg[2], *seg[3])
        if isinstance(item, dict) and item.get("closed"):
            p.close()
        p.stroke(2 * hw, pathops.LineCap.ROUND_CAP, pathops.LineJoin.ROUND_JOIN, 4)
        p.convertConicsToQuads(0.1)
        acc.addPath(p)
    acc.simplify(fix_winding=True, keep_starting_points=False)
    return acc


def glyph(codepoint: int):
    """按码位取二创字形；没有就返回 None。

    数据结构：`{"hw": 半宽, "strokes": [{"closed": 是否围框, "segs": [贝塞尔段...]}]}`。
    每个 `seg` 是 4 个控制点，首尾与相邻段相接。
    """
    d = MEASURED_STROKES.get(f"{codepoint:04X}")
    if d is None:
        return None
    return _stroked(d["strokes"], d["hw"])


